import { useSyncExternalStore } from "react";

/** Simple EN / Sinhala switch. The English text is the key; a missing Sinhala line falls back to English. */
export type Lang = "en" | "si";
const KEY = "lifta.lang";
let lang: Lang = (() => { try { return localStorage.getItem(KEY) === "si" && localStorage.getItem("lifta.sinhala") === "1" ? "si" : "en"; } catch { return "en"; } })();
const SKEY = "lifta.sinhala";
// the owner switches Sinhala on or off for the whole shop (Settings); off means English only and no language button
let allowed = (() => { try { return localStorage.getItem(SKEY) === "1"; } catch { return false; } })();
const subscribers = new Set<() => void>();

export function setLang(next: Lang) {
  if (next === lang) return;
  lang = next;
  try { localStorage.setItem(KEY, next); } catch { /* private mode */ }
  try { document.documentElement.lang = next; } catch { /* no document */ }
  subscribers.forEach((notify) => notify());
}
export function getLang(): Lang { return lang; }
export function setSinhalaAllowed(on: boolean) {
  if (on === allowed) { if (!on) setLang("en"); return; }
  allowed = on;
  try { localStorage.setItem(SKEY, on ? "1" : "0"); } catch { /* private mode */ }
  if (!on) setLang("en");
  subscribers.forEach((notify) => notify());
}
export function useSinhalaAllowed(): boolean {
  return useSyncExternalStore((notify) => { subscribers.add(notify); return () => { subscribers.delete(notify); }; }, () => allowed);
}
/** Call in a component so it re-renders when the language changes. */
export function useLang(): Lang {
  return useSyncExternalStore((notify) => { subscribers.add(notify); return () => { subscribers.delete(notify); }; }, () => lang);
}
try { document.documentElement.lang = lang; } catch { /* no document */ }

export function t(text: string, vars?: Record<string, string | number>): string {
  let out = (lang === "si" && SI[text]) || text;
  if (vars) for (const k of Object.keys(vars)) out = out.split("{" + k + "}").join(String(vars[k]));
  return out;
}

